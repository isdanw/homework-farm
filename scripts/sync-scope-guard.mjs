#!/usr/bin/env node
/**
 * sync-scope-guard.mjs —— 把 scopeGuard 的 canonical 源同步到各云函数目录副本。
 *
 * 用法：
 *   node scripts/sync-scope-guard.mjs          写入所有副本
 *   node scripts/sync-scope-guard.mjs --check  只校验，不写入（测试/部署前用）
 *
 * 为什么是「复制」而不是 require('../_shared/scopeGuard')：
 *   本项目云函数是逐个目录独立部署（tcb fn deploy --dir cloudfunctions/<name>），
 *   上传时只打包该目录，云端不存在 `../_shared`，require 会直接 MODULE_NOT_FOUND。
 *
 * 副本格式 = 生成头（含 canonical sha256）+ canonical 原文（逐字节相同）。
 * 因此改 canonical 后必须重跑本脚本；`scripts/test-scope-guard.cjs` 用同一哈希校验，
 * 副本漂移会让 npm test 变红。
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');

const CANONICAL = join(ROOT, 'cloudfunctions/_shared/scopeGuard.js');

/** 需要作用域守卫的写入口云函数（新增写入口时在这里登记）
 *  webAdminQuery 是**只读**函数，登记它只为复用 childrenOf（孩子清单不得两套定义）。 */
export const TARGETS = ['tutorSync', 'tutorChat', 'tutorRetest', 'webAdminWrite', 'syncData', 'dailyReset', 'webAdminQuery', 'examService'];

const BANNER_MARK = 'AUTO-GENERATED by scripts/sync-scope-guard.mjs';
const HASH_RE = /canonical-sha256:\s*([0-9a-f]{64})/;

export function sha256(text) {
  return createHash('sha256').update(text, 'utf8').digest('hex');
}

export function banner(hash) {
  return [
    '/**',
    ' * ⚠️ AUTO-GENERATED —— 请勿直接编辑本文件。',
    ' * 源文件：cloudfunctions/_shared/scopeGuard.js（canonical）',
    ' * 重新生成：node scripts/sync-scope-guard.mjs',
    ` * ${BANNER_MARK}`,
    ` * canonical-sha256: ${hash}`,
    ' */',
    '',
  ].join('\n');
}

export function expectedCopy(canonicalText) {
  return banner(sha256(canonicalText)) + canonicalText;
}

function main() {
  const check = process.argv.indexOf('--check') >= 0;
  const canonicalText = readFileSync(CANONICAL, 'utf8');
  const want = expectedCopy(canonicalText);
  let bad = 0;
  let written = 0;
  let skipped = 0;

  for (const fn of TARGETS) {
    const target = join(ROOT, 'cloudfunctions', fn, 'scopeGuard.js');
    const dir = dirname(target);
    if (!existsSync(dir)) {
      console.log(`  跳过  ${fn}（目录不存在）`);
      skipped++;
      continue;
    }
    if (check) {
      if (!existsSync(target)) {
        console.log(`  ✗ ${fn} 副本缺失：${target}`);
        bad++;
        continue;
      }
      const got = readFileSync(target, 'utf8');
      if (got !== want) {
        const m = HASH_RE.exec(got);
        console.log(`  ✗ ${fn} 副本与 canonical 不一致`);
        console.log(`      canonical ${sha256(canonicalText)}`);
        console.log(`      copy      ${m ? m[1] : '(缺少哈希行)'}`);
        bad++;
      } else {
        console.log(`  ✓ ${fn}`);
      }
      continue;
    }
    if (existsSync(target) && readFileSync(target, 'utf8') === want) {
      console.log(`  未变  ${fn}`);
    } else {
      writeFileSync(target, want, 'utf8');
      console.log(`  写入  ${fn} → cloudfunctions/${fn}/scopeGuard.js`);
      written++;
    }
  }

  console.log(`canonical sha256 = ${sha256(canonicalText)}`);
  console.log(`写入 ${written} · 跳过 ${skipped} · 不一致 ${bad}`);

  if (bad > 0) {
    if (check) console.error('\n哈希锁失败：请执行 `node scripts/sync-scope-guard.mjs` 重新生成副本。');
    process.exit(1);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
